#!/usr/bin/env python3
"""Generate src/parser/itl_tables.cpp from the reference iridium-toolkit itl.py."""
import os
import sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ref = os.path.join(root, "references", "iridium-toolkit")
sys.path.insert(0, ref)
import itl  # noqa: E402

out = os.path.join(root, "src", "parser", "itl_tables.cpp")
with open(out, "w", encoding="utf-8", newline="\n") as f:
    f.write("// Generated by scripts/gen_itl_tables.py - do not edit by hand.\n")
    f.write('#include "parser/itl_tables.h"\n\n')
    f.write("const char *const kItlPrsHdr[3] = {\n")
    for x in itl.PRS_HDR:
        f.write('    "%s",\n' % x)
    f.write("};\n\n")
    f.write("const char *const kItlPrsPlanes[6] = {\n")
    for x in itl.PRS_PLANES:
        f.write('    "%s",\n' % x)
    f.write("};\n\n")
    f.write("const char *const kItlPrsList[512] = {\n")
    for i, x in enumerate(itl.PRS_LIST):
        f.write('    "%s",\n' % x)
    f.write("};\n\n")
    f.write("const char *const kItlPrsPlanesV1[6] = {\n")
    for x in itl.PRS_PLANES_V1:
        f.write('    "%s",\n' % x)
    f.write("};\n\n")
    f.write("const char *const kItlPrsListV1[128] = {\n")
    for x in itl.PRS_LIST_V1:
        f.write('    "%s",\n' % x)
    f.write("};\n")
print("wrote", out, "lists:", len(itl.PRS_LIST), len(itl.PRS_LIST_V1))
